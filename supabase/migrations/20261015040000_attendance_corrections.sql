alter table public.correction_pointage
  add column if not exists revision bigint;

with ranked_corrections as (
  select
    correction.id,
    row_number() over (
      partition by correction.id_pointage
      order by correction.date_correction, correction.id
    ) as revision
  from public.correction_pointage as correction
)
update public.correction_pointage as correction
set revision = ranked_corrections.revision
from ranked_corrections
where correction.id = ranked_corrections.id
  and correction.revision is null;

alter table public.correction_pointage
  alter column revision set not null;

do $$
begin
  if not exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'correction_pointage'
      and column_name = 'revision'
      and is_identity = 'YES'
  ) then
    alter table public.correction_pointage
      alter column revision add generated by default as identity;
  end if;
end;
$$;

select setval(
  pg_get_serial_sequence('public.correction_pointage', 'revision'),
  coalesce(max(revision), 0) + 1,
  false
)
from public.correction_pointage;

create unique index if not exists correction_pointage_revision_idx
  on public.correction_pointage (id_pointage, revision);

revoke insert, update, delete on table public.correction_pointage
  from anon, authenticated;

drop policy if exists correction_insert_admin_roles
  on public.correction_pointage;

create or replace function public.correct_attendance_pointage(
  target_pointage uuid,
  operator_user_id uuid,
  corrected_at timestamptz,
  correction_reason text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  original_pointage public.pointage%rowtype;
  effective_timestamp timestamptz;
begin
  if (select auth.role()) is distinct from 'service_role' then
    raise exception using
      errcode = '42501',
      message = 'Only the trusted service may correct attendance.';
  end if;

  if target_pointage is null
    or corrected_at is null
    or correction_reason is null
    or length(btrim(correction_reason)) < 5
    or length(btrim(correction_reason)) > 500
  then
    raise exception using
      errcode = '22023',
      message = 'The attendance correction is invalid.';
  end if;

  if not exists (
    select 1
    from public.personnel as operator_person
    join public.acces_utilisateur as operator_role
      on operator_role.id_personnel = operator_person.id
    where operator_person.auth_user_id = operator_user_id
      and operator_person.actif
      and operator_person.acces_approuve
      and operator_role.role in (
        'rh'::public.app_role,
        'scolarite'::public.app_role
      )
      and operator_role.date_debut <= now()
      and (
        operator_role.date_fin is null
        or operator_role.date_fin > now()
      )
  ) then
    raise exception using
      errcode = '42501',
      message = 'An active RH or Scolarité role is required.';
  end if;

  select pointage.*
  into original_pointage
  from public.pointage as pointage
  where pointage.id = target_pointage
  for update;

  if not found then
    raise exception using
      errcode = 'P0002',
      message = 'The attendance event was not found.';
  end if;

  select correction.nouvelle_valeur
  into effective_timestamp
  from public.correction_pointage as correction
  where correction.id_pointage = target_pointage
  order by correction.revision desc
  limit 1;

  effective_timestamp := coalesce(
    effective_timestamp,
    original_pointage.date_heure
  );

  if corrected_at = effective_timestamp
    or (corrected_at at time zone 'Africa/Casablanca')::date
      <> (original_pointage.date_heure at time zone 'Africa/Casablanca')::date
  then
    raise exception using
      errcode = '22023',
      message = 'The corrected time must differ and remain on the original local day.';
  end if;

  insert into public.correction_pointage (
    id_pointage,
    id_rh,
    motif,
    ancienne_valeur,
    nouvelle_valeur
  )
  values (
    target_pointage,
    operator_user_id,
    btrim(correction_reason),
    effective_timestamp,
    corrected_at
  );
end;
$$;

revoke all on function public.correct_attendance_pointage(
  uuid,
  uuid,
  timestamptz,
  text
) from public, anon, authenticated;
grant execute on function public.correct_attendance_pointage(
  uuid,
  uuid,
  timestamptz,
  text
) to service_role;
